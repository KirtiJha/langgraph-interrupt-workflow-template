// Generates app/theme.css: every palette shade as an RGB CSS variable, with a
// dark-mode remap (light tints ↔ deep tints), so existing classes like
// bg-rose-50 / text-stone-600 work in both themes without dark: variants.
// Run: node scripts/gen-theme.js
const fs = require("fs");
const colors = require("tailwindcss/colors");

const FAMILIES = { stone: colors.stone, gray: colors.stone, violet: colors.violet, rose: colors.rose, emerald: colors.emerald,
  amber: colors.amber, sky: colors.sky, green: colors.emerald, ember: colors.orange };
const SHADES = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"];
// Mirror the light end onto the dark end; keep 500/600 (solid buttons, accents).
const DARK = { 50: "950", 100: "900", 200: "800", 300: "700", 400: "600", 500: "500", 600: "600", 700: "300", 800: "200", 900: "100", 950: "50" };
// Tinted backgrounds (50/100) read too strong when fully mirrored; mix them toward the page.
const rgb = (hex) => { const n = parseInt(hex.slice(1), 16); return [(n >> 16) & 255, (n >> 8) & 255, n & 255]; };
const mix = (a, b, t) => a.map((v, i) => Math.round(v * (1 - t) + b[i] * t));
const PAGE_DARK = rgb("#0f0d0b");
const fmt = (c) => c.join(" ");

let light = [], dark = [];
for (const [fam, pal] of Object.entries(FAMILIES)) {
  for (const s of SHADES) {
    light.push(`  --c-${fam}-${s}: ${fmt(rgb(pal[s]))};`);
    const neutral = fam === "stone" || fam === "gray";
    // Neutral muted text (400/500) must stay readable on a dark page: lift it.
    // Neutrals: secondary text (500/600) lifts to 400 and muted (400) to 500.
    const NEUTRAL_TEXT = { 400: "500", 500: "400", 600: "400" };
    const shade = neutral && NEUTRAL_TEXT[s] ? NEUTRAL_TEXT[s] : DARK[s];
    let c = rgb(pal[shade]);
    if (!neutral && (s === "50" || s === "100")) c = mix(c, PAGE_DARK, s === "50" ? 0.68 : 0.5);
    if ((fam === "stone" || fam === "gray") && s === "50") c = rgb("#1a1715");
    if ((fam === "stone" || fam === "gray") && s === "100") c = rgb("#24201d");
    dark.push(`  --c-${fam}-${s}: ${fmt(c)};`);
  }
}
const extraLight = ["  --c-white: 255 255 255;", "  --paper: 250 248 243;", "  --ink: 28 25 23;", "  --chip-text: 28 25 23;", "  color-scheme: light;"];
const extraDark = ["  --c-white: 28 25 23;", "  --paper: 15 13 11;", "  --ink: 245 243 239;", "  --chip-text: 245 243 239;", "  color-scheme: dark;"];

const css = `/* Generated by scripts/gen-theme.js — do not edit by hand. */
:root {
${light.concat(extraLight).join("\n")}
}
:root[data-theme="dark"] {
${dark.concat(extraDark).join("\n")}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${dark.concat(extraDark).map((l) => "  " + l).join("\n")}
  }
}
`;
fs.writeFileSync(__dirname + "/../app/theme.css", css);
console.log("wrote app/theme.css");
